"""FastAPI app: the bottle, the reading, the GTM engine, webhooks, and the static UI.

Run:  uv run uvicorn api.main:app --reload --port 8000   then open http://localhost:8000
"""
from __future__ import annotations

import asyncio
import html
import json
import re
from contextlib import asynccontextmanager
from pathlib import Path

from fastapi import FastAPI, HTTPException, Request
from fastapi.responses import FileResponse, HTMLResponse, PlainTextResponse, StreamingResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel

from .engine import Engine, Session
from .insight.hit import feature_label
from .ml import backtest

WEB = Path(__file__).resolve().parents[1] / "apps" / "web"
STATE: dict = {}


@asynccontextmanager
async def lifespan(app: FastAPI):
    eng = await asyncio.to_thread(Engine)
    STATE["engine"] = eng
    STATE["backtest_task"] = asyncio.create_task(asyncio.to_thread(backtest.cached, eng.world, eng.graph))
    yield


app = FastAPI(title="Intuition in a bottle", lifespan=lifespan)
app.mount("/static", StaticFiles(directory=WEB), name="static")


def eng() -> Engine:
    return STATE["engine"]


def sess(sid: str) -> Session:
    s = eng().sessions.get(sid)
    if not s:
        raise HTTPException(404, "no such session")
    return s


class Text(BaseModel):
    text: str


class DraftReq(BaseModel):
    account_id: int


class Approve(BaseModel):
    body: str | None = None


class Reply(BaseModel):
    text: str
    draft_id: str | None = None
    sender: str | None = None
    subject: str | None = None


