@app.post("/api/sessions/{sid}/reading")
async def reading(sid: str):
    s = sess(sid)
    if not s.bottle.answers:
        raise HTTPException(400, "interview first")
    cards = await s.run_reading()
    return {"cards": [c.model_dump() for c in cards]}


