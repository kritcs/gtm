@app.get("/reply/{draft_id}", response_class=HTMLResponse, include_in_schema=False)
def reply_page(draft_id: str):
    """Phone page for the demo ending: a teammate taps Reply and the webhook fires."""
    return (WEB / "reply.html").read_text().replace("{{DRAFT_ID}}", html.escape(draft_id))


@app.get("/api/posts/{post_id}", response_class=HTMLResponse)
def post_page(post_id: int, request: Request):
    p = eng().graph.posts.get(post_id)
    if not p:
        raise HTTPException(404, "no such post")
    w = eng().world
    company = w.companies[p.company_id].name if p.company_id is not None else None
    data = {"id": p.id, "date": p.date, "kind": p.kind, "author": p.author, "title": p.title,
            "company": company, "text": p.text, "simulated": True}
    if "application/json" in request.headers.get("accept", ""):
        return HTMLResponse(json.dumps(data), media_type="application/json")
    title = html.escape(p.title or (f"{company} is hiring" if company else "Post"))
    return f"""<!doctype html><meta charset=utf-8><meta name=viewport content="width=device-width">
<title>{title}</title><link rel=stylesheet href="/static/styles.css">
<body class="receipt-page"><article class="receipt-doc"><p class="eyebrow">Simulated HN post · {p.date} · {html.escape(p.author)}</p>
<h1>{title}</h1><pre>{html.escape(p.text)}</pre>
<p class="fine">Generated by the simulated market (seed {w.seed}). In production this links to news.ycombinator.com.</p></article></body>"""


